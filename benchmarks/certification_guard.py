"""Machine-checkable benchmark certification guard for MIRAGE.

Enforces strict gating rules preventing automated benchmark reports from
emitting 'CERTIFIED' when prerequisites for full academic certification are unmet:
1. External benchmark datasets must be full academic corpora, not curated fixtures.
2. Calibration fitting data and evaluation data must be disjoint (zero test leakage).
3. Cross-model evaluation must execute live model inference, not simulation.
4. Baseline heuristic proxies must remain explicitly qualified.
5. Sample sizes must meet native dataset requirements and asymptotic power thresholds.
"""

from dataclasses import asdict, dataclass
from typing import Any

# Dataset-native full academic corpus size requirements per literature specifications
NATIVE_ACADEMIC_CORPUS_REQUIREMENTS = {
    "HaluEval": 10000,
    "TruthfulQA": 817,
    "FActScore": 183,
    "MMHAL-Bench": 96,
}


@dataclass
class CertificationAuditResult:
    """Detailed result of machine-checkable certification audit."""

    status: str  # "TIER_1_HARNESS_COMPLETE" | "TIER_2_ACADEMIC_CERTIFIED"
    is_certified: bool
    tier_1_readiness: bool
    tier_2_readiness: bool
    gate_checks: dict[str, dict[str, Any]]
    unmet_prerequisites: list[str]
    summary: str

    def to_dict(self) -> dict[str, Any]:
        """Serialize audit result to dictionary."""
        return asdict(self)


class BenchmarkCertificationGuard:
    """Machine-checkable gate ensuring certification is never emitted from demonstration runs."""

    def audit_certification_readiness(self, report_payload: dict[str, Any]) -> CertificationAuditResult:
        """Audit a benchmark report payload against all mandatory academic certification criteria.

        Args:
            report_payload: Structured report dictionary generated by run_benchmarks.py.

        Returns:
            CertificationAuditResult with explicit status and unmet prerequisites.
        """
        gate_checks: dict[str, dict[str, Any]] = {}
        unmet_prerequisites: list[str] = []

        # ----------------------------------------------------------------------
        # Check 1: External Benchmark Corpus Tier (No Fixtures for Certification)
        # ----------------------------------------------------------------------
        datasets = report_payload.get("datasets", {})
        provenance = report_payload.get("dataset_provenance", {})
        fixture_datasets: list[str] = []

        for d_name in ["HaluEval", "TruthfulQA", "FActScore", "MMHAL-Bench"]:
            meta = provenance.get(d_name, {}) or datasets.get(d_name, {}).get("metadata", {})
            corpus_type = meta.get("corpus_type", "unknown")
            if corpus_type != "external_academic_corpus":
                fixture_datasets.append(d_name)

        check_1_passed = len(fixture_datasets) == 0
        gate_checks["no_fixture_datasets"] = {
            "passed": check_1_passed,
            "fixture_datasets": fixture_datasets,
            "description": "All datasets must be full external academic corpora, not demonstration fixtures.",
        }
        if not check_1_passed:
            unmet_prerequisites.append(
                f"Benchmark datasets running on demonstration fixtures rather than external corpora: {fixture_datasets}"
            )

        # ----------------------------------------------------------------------
        # Check 2: Dataset-Native Sample Size Adequacy
        # ----------------------------------------------------------------------
        sample_size_deficits: dict[str, dict[str, int]] = {}
        for d_name, required_n in NATIVE_ACADEMIC_CORPUS_REQUIREMENTS.items():
            actual_n = datasets.get(d_name, {}).get("sample_count", 0)
            if actual_n < required_n:
                sample_size_deficits[d_name] = {"actual": actual_n, "required": required_n}

        check_2_passed = len(sample_size_deficits) == 0
        gate_checks["native_sample_size_adequacy"] = {
            "passed": check_2_passed,
            "deficits": sample_size_deficits,
            "description": "Each benchmark must meet its literature-defined native academic corpus sample size.",
        }
        if not check_2_passed:
            unmet_prerequisites.append(f"Sample size below literature requirements: {sample_size_deficits}")

        # ----------------------------------------------------------------------
        # Check 3: Calibration Fitting / Evaluation Separation (Zero Leakage)
        # ----------------------------------------------------------------------
        cal_results = report_payload.get("calibration_3way", [])
        cal_leakage_detected = False
        cal_smoke_test_only = False

        for c in cal_results:
            eval_type = c.get("evaluation_type", "")
            if eval_type == "methodology_smoke_test_only":
                cal_smoke_test_only = True
            if c.get("fitting_sample_count", 0) > 0 and c.get("evaluation_sample_count", 0) == 0:
                cal_leakage_detected = True

        check_3_passed = not cal_leakage_detected and not cal_smoke_test_only
        gate_checks["calibration_separation"] = {
            "passed": check_3_passed,
            "smoke_test_only": cal_smoke_test_only,
            "leakage_detected": cal_leakage_detected,
            "description": "Calibration evaluation must be strictly out-of-sample on separate held-out split.",
        }
        if not check_3_passed:
            if cal_smoke_test_only:
                unmet_prerequisites.append(
                    "Calibration evaluation is currently labeled 'methodology smoke test only' "
                    "on small demonstration split."
                )
            if cal_leakage_detected:
                unmet_prerequisites.append(
                    "Calibration evaluation data overlaps with fitting data; out-of-sample generalization unverified."
                )

        # ----------------------------------------------------------------------
        # Check 4: Generator Model Execution Reality (No Simulation for Certification)
        # ----------------------------------------------------------------------
        cross_model = report_payload.get("cross_model_generalization", [])
        simulation_models: list[str] = []

        for m in cross_model:
            eval_type = m.get("evaluation_type", "")
            if "Simulation" in eval_type:
                simulation_models.append(m.get("model_name", "unknown"))

        check_4_passed = len(simulation_models) == 0 and len(cross_model) > 0
        gate_checks["live_generator_execution"] = {
            "passed": check_4_passed,
            "simulation_models": simulation_models,
            "description": "Cross-model generator evaluation must execute live API/model generation, not simulation.",
        }
        if not check_4_passed:
            unmet_prerequisites.append(
                f"Cross-model evaluation executed via stylistic perturbation simulation: {simulation_models}"
            )

        # ----------------------------------------------------------------------
        # Check 5: Baseline Qualification Integrity
        # ----------------------------------------------------------------------
        baselines = report_payload.get("baselines", [])
        unqualified_proxies: list[str] = []

        for b in baselines:
            bid = b.get("baseline_id", "")
            fidelity = b.get("implementation_fidelity", "")
            bname = b.get("baseline_name", "")
            # Proxies B2-B5 must be explicitly marked as Heuristic Proxy
            if bid in ("B2", "B3", "B4", "B5"):
                if fidelity != "Heuristic Proxy" or "Proxy" not in bname:
                    unqualified_proxies.append(bid)

        check_5_passed = len(unqualified_proxies) == 0 and len(baselines) == 7
        gate_checks["baseline_qualification"] = {
            "passed": check_5_passed,
            "unqualified_proxies": unqualified_proxies,
            "description": "All proxy baselines (B2-B5) must maintain explicit 'Heuristic Proxy' fidelity labels.",
        }
        if not check_5_passed:
            unmet_prerequisites.append(
                f"Baselines lacking explicit heuristic proxy qualification: {unqualified_proxies}"
            )

        # ----------------------------------------------------------------------
        # Check 6: Adversarial Robustness Decoupling (No Token-Absence Inflation)
        # ----------------------------------------------------------------------
        adversarial = report_payload.get("adversarial_robustness", [])
        atk03_uncertified = False

        for adv in adversarial:
            if adv.get("attack_id") == "ATK-03":
                # ATK-03 must be classified as known metric-sensitivity harness test
                if (
                    adv.get("empirical_robustness_certified", True) is not False
                    or adv.get("classification") != "known_metric_sensitivity_harness_test"
                ):
                    atk03_uncertified = True

        check_6_passed = not atk03_uncertified
        gate_checks["adversarial_decoupling"] = {
            "passed": check_6_passed,
            "description": (
                "ATK-03 must be classified as a metric-sensitivity harness test, "
                "not uncoupled robustness certification."
            ),
        }
        if not check_6_passed:
            unmet_prerequisites.append(
                "ATK-03 hallucinated citations incorrectly claimed empirical "
                "robustness certification despite metric coupling."
            )

        # ----------------------------------------------------------------------
        # Check 7: Complete Suite Execution (No Partial Run Certification)
        # ----------------------------------------------------------------------
        has_all_datasets = len(datasets) == 4
        has_all_baselines = len(baselines) == 7
        has_all_cross_model = len(cross_model) == 3
        has_all_adversarial = len(adversarial) == 4
        has_calibration = len(cal_results) >= 3

        check_7_passed = (
            has_all_datasets and has_all_baselines and has_all_cross_model and has_all_adversarial and has_calibration
        )
        gate_checks["complete_suite_execution"] = {
            "passed": check_7_passed,
            "has_all_datasets": has_all_datasets,
            "has_all_baselines": has_all_baselines,
            "has_all_cross_model": has_all_cross_model,
            "has_all_adversarial": has_all_adversarial,
            "has_calibration": has_calibration,
            "description": (
                "All benchmark suites (datasets, baselines, ablations, calibration, "
                "cross-model, adversarial) must execute fully."
            ),
        }
        if not check_7_passed:
            unmet_prerequisites.append(
                "Partial evaluation run detected; full scientific certification requires complete suite execution."
            )

        # ----------------------------------------------------------------------
        # Determination: Tier 1 vs Tier 2
        # ----------------------------------------------------------------------
        all_passed = (
            check_1_passed
            and check_2_passed
            and check_3_passed
            and check_4_passed
            and check_5_passed
            and check_6_passed
            and check_7_passed
        )

        tier_1_ready = len(datasets) == 4 and len(baselines) == 7 and len(cross_model) == 3

        if all_passed:
            status = "TIER_2_ACADEMIC_CERTIFIED"
            summary = "All Tier 2 academic certification criteria satisfied on full external corpora."
        else:
            status = "TIER_1_HARNESS_COMPLETE"
            summary = (
                f"Tier 1 engineering harness verified ({len(unmet_prerequisites)} Tier 2 prerequisites outstanding)."
            )

        return CertificationAuditResult(
            status=status,
            is_certified=all_passed,
            tier_1_readiness=tier_1_ready,
            tier_2_readiness=all_passed,
            gate_checks=gate_checks,
            unmet_prerequisites=unmet_prerequisites,
            summary=summary,
        )
