#!/usr/bin/env python3
"""MIRAGE 3.0 — AWS Secrets Manager Safe Serializer for Docker Compose.

Fetches secret key-value JSON from AWS Secrets Manager (or accepts JSON input)
and safely serializes keys and values into a production-safe, properly quoted
.env file for Docker Compose without leaking secrets or breaking on special characters.

Security Invariants:
1. Rejects unfilled placeholder values (REPLACE_WITH_*, placeholder, changeme) in staging/production.
2. Escapes special characters (quotes, backslashes, dollar signs) safely for Docker Compose.
3. Sets restrictive POSIX file permissions (0600 - owner read/write only) on the destination file.
4. Redacts secret values from console logs, diagnostic output, and tracebacks.

Usage:
    python scripts/fetch_secrets.py --secret-id <SECRET_NAME> --region <AWS_REGION> --output .env
    python scripts/fetch_secrets.py --input-json-file secrets.json --output .env --environment staging
"""

from __future__ import annotations

import argparse
import json
import os
import re
import stat
import subprocess
import sys
from pathlib import Path


def is_insecure_placeholder(val: str | None) -> bool:
    """Check if value is empty, a known development default, or an unfilled placeholder."""
    if val is None or not str(val).strip():
        return True
    low = str(val).strip().lower()
    return (
        low.startswith("replace_with_")
        or low.startswith("your_")
        or "placeholder" in low
        or "changeme" in low
        or "example" in low
        or "min32chars" in low
        or "mirage_dev_secret" in low
        or "mirage_redis_secret" in low
        or "mirage_rabbit_secret" in low
        or "mirage_celery_secret" in low
        or "mirage_mongo_secret" in low
        or "mirage_qdrant_secret" in low
        or "mirage_grafana_secret" in low
    )


def serialize_env_value(val: str) -> str:
    r"""Safely escape and quote a string value for Docker Compose .env files.

    Rules:
    - If value contains no whitespace, quotes, backslashes, or dollar signs, return as-is.
    - If value contains single quotes, double-quote it and escape " and \.
      Also escape $ to $$ to prevent accidental compose variable interpolation.
    - Otherwise single-quote it for literal interpretation.
    """
    if val == "":
        return '""'

    # If it's a simple alphanumeric string with underscores/hyphens/colons/dots/slashes
    if re.fullmatch(r"^[a-zA-Z0-9_\-\.\:\/]+$", val):
        return val

    # If there are no single quotes, single quoting is strictly literal in dotenv/Compose
    if "'" not in val and "\n" not in val and "\r" not in val:
        return f"'{val}'"

    # Otherwise double-quote and escape backslashes, double quotes, and dollar signs
    escaped = val.replace("\\", "\\\\").replace('"', '\\"').replace("$", "$$")
    # Escape newlines
    escaped = escaped.replace("\r", "\\r").replace("\n", "\\n")
    return f'"{escaped}"'


def serialize_secrets_to_env(
    secrets: dict[str, str],
    environment: str = "staging",
    allow_placeholders: bool = False,
) -> tuple[str, list[str]]:
    """Serialize secrets dictionary to .env file content.

    Returns:
        (serialized_content, list_of_defects)
    """
    defects: list[str] = []
    lines: list[str] = [
        "# MIRAGE 3.0 Environment Configuration",
        "# Auto-generated by fetch_secrets.py — DO NOT COMMIT OR EXPOSE",
        f"# Environment: {environment}",
        "",
    ]

    for key, raw_val in sorted(secrets.items()):
        val_str = str(raw_val) if raw_val is not None else ""
        if not allow_placeholders and environment in ("staging", "production"):
            if is_insecure_placeholder(val_str):
                defects.append(f"Secret '{key}' contains an unfilled placeholder or default development value")

        quoted = serialize_env_value(val_str)
        lines.append(f"{key}={quoted}")

    lines.append("")  # trailing newline
    return "\n".join(lines), defects


def fetch_secret_from_aws(secret_id: str, region: str) -> dict[str, str]:
    """Retrieve secret string from AWS Secrets Manager using aws cli."""
    cmd = [
        "aws",
        "secretsmanager",
        "get-secret-value",
        "--secret-id",
        secret_id,
        "--region",
        region,
        "--output",
        "json",
    ]
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True, check=True)
        data = json.loads(proc.stdout)
        secret_str = data.get("SecretString", "{}")
        parsed = json.loads(secret_str)
        if not isinstance(parsed, dict):
            raise ValueError(f"Secret payload must be a JSON object, got {type(parsed)}")
        return {str(k): str(v) for k, v in parsed.items()}
    except subprocess.CalledProcessError as cpe:
        # Redact any sensitive output in errors
        err_msg = cpe.stderr.strip() if cpe.stderr else str(cpe)
        raise RuntimeError(f"AWS Secrets Manager retrieval failed: {err_msg}") from cpe


def write_env_file_secure(path: Path, content: str) -> None:
    """Write content to file and set 0600 permissions where supported."""
    path.write_text(content, encoding="utf-8")
    # On POSIX systems, restrict permissions to owner read/write only
    if os.name == "posix":
        try:
            path.chmod(stat.S_IRUSR | stat.S_IWUSR)
        except OSError:
            pass


def main() -> int:
    parser = argparse.ArgumentParser(description="Fetch and safely serialize AWS secrets for Docker Compose")
    parser.add_argument("--secret-id", help="AWS Secrets Manager secret name or ARN")
    parser.add_argument("--region", default=os.environ.get("AWS_REGION", "us-east-1"), help="AWS Region")
    parser.add_argument("--output", "-o", default=".env", help="Destination .env file path (default: .env)")
    parser.add_argument("--input-json-file", help="Path to local JSON file for testing without AWS connectivity")
    parser.add_argument("--environment", default="staging", choices=["development", "staging", "production"])
    parser.add_argument("--allow-placeholders", action="store_true", help="Allow placeholder values")
    parser.add_argument("--dry-run", action="store_true", help="Validate and serialize without writing to disk")

    args = parser.parse_args()

    # Load secrets
    if args.input_json_file:
        raw_text = Path(args.input_json_file).read_text(encoding="utf-8")
        secrets_dict = json.loads(raw_text)
    elif args.secret_id:
        try:
            secrets_dict = fetch_secret_from_aws(args.secret_id, args.region)
        except Exception as exc:
            print(f"ERROR: {exc}", file=sys.stderr)
            return 1
    else:
        print("ERROR: Either --secret-id or --input-json-file must be provided", file=sys.stderr)
        return 1

    content, defects = serialize_secrets_to_env(
        secrets_dict,
        environment=args.environment,
        allow_placeholders=args.allow_placeholders,
    )

    if defects:
        print(f"CONFIGURATION BLOCKED: {len(defects)} security defect(s) detected:", file=sys.stderr)
        for defect in defects:
            print(f"  - {defect}", file=sys.stderr)
        return 2

    if args.dry_run:
        print(f"Successfully validated and serialized {len(secrets_dict)} secret keys (dry-run).")
        return 0

    out_path = Path(args.output).resolve()
    write_env_file_secure(out_path, content)
    print(f"Successfully generated secure environment file: {out_path} ({len(secrets_dict)} keys)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
