"""MIRAGE 3.0 Developer Quickstart & Onboarding Script.

One-command setup and verification for developers cloning the MIRAGE repository.
Runs against the local Docker development environment:
1. Checks gateway & infrastructure health (/v1/health, /v1/ready).
2. Provisions a local developer sandbox tenant with an active API key.
3. Automatically writes .env.local for local tooling and SDK examples.
4. Executes a full 5-Gate Assurance pipeline verification.
5. Verifies the Governed MCP (Model Context Protocol) JSON-RPC bridge.
6. Outputs a terminal summary with actionable next steps.
"""

import os
import sys
import uuid
from typing import Any, cast

try:
    import httpx
except ImportError:
    print("[ERROR] httpx is required for quickstart. Please run: pip install httpx")
    sys.exit(1)


BASE_URL = os.environ.get("MIRAGE_BASE_URL", "http://localhost:8000")


def print_banner() -> None:
    print("\n" + "=" * 70)
    print("  MIRAGE 3.0 - AI Execution Assurance Platform")
    print("  'Control AI before it acts. Verify AI after it acts.'")
    print("=" * 70 + "\n")


def check_health(client: httpx.Client) -> bool:
    print("[1/5] Checking MIRAGE Gateway & Infrastructure Health...")
    try:
        resp = client.get(f"{BASE_URL}/v1/health", timeout=5.0)
        if resp.status_code != 200:
            print(f"  [FAIL] Gateway returned HTTP {resp.status_code}: {resp.text}")
            return False
        health_data = resp.json()
        print(f"  [PASS] Gateway status: {health_data.get('status', 'OK')} (v{health_data.get('version', '3.0')})")
        return True
    except Exception as exc:
        print(f"  [FAIL] Could not connect to {BASE_URL}: {exc}")
        print("         Make sure Docker containers are running: 'docker compose up -d'")
        return False


def provision_sandbox_tenant(client: httpx.Client) -> dict[str, Any] | None:
    print("\n[2/5] Provisioning Local Developer Sandbox Tenant...")
    payload = {
        "name": "Local Quickstart Org",
        "admin_email": f"developer_{uuid.uuid4().hex[:6]}@mirage.local",
        "tier": "developer",
    }
    try:
        resp = client.post(f"{BASE_URL}/v1/auth/register-tenant", json=payload, timeout=10.0)
        if resp.status_code != 201:
            print(f"  [FAIL] Failed to register sandbox tenant: HTTP {resp.status_code}: {resp.text}")
            return None
        data = resp.json()
        print(f"  [PASS] Tenant ID:   {data['tenant_id']}")
        print(f"  [PASS] Admin User:  {data['admin_user_id']}")
        print(f"  [PASS] API Key:     {data['api_key'][:16]}...[PROTECTED]")

        # Write .env.local for local SDK and test runs
        env_content = (
            f"# Auto-generated by MIRAGE quickstart on {data.get('created_at')}\n"
            f"MIRAGE_BASE_URL={BASE_URL}\n"
            f"MIRAGE_API_KEY={data['api_key']}\n"
            f"MIRAGE_TENANT_ID={data['tenant_id']}\n"
        )
        with open(".env.local", "w", encoding="utf-8") as f:
            f.write(env_content)
        print("  [PASS] Saved credentials to .env.local")
        return cast(dict[str, Any], data)
    except Exception as exc:
        print(f"  [FAIL] Exception during sandbox tenant provisioning: {exc}")
        return None


def verify_gate4_output_assurance(client: httpx.Client, api_key: str) -> bool:
    print("\n[3/5] Verifying Gate 4 (Output Assurance / HRS Verification Engine)...")
    headers = {"X-API-Key": api_key}
    req = {
        "prompt": "What is the capital of France and what is the speed of light?",
        "response": "The capital of France is Paris. Light travels at approximately 300,000 kilometers per second.",
    }
    try:
        resp = client.post(f"{BASE_URL}/v1/verify", json=req, headers=headers, timeout=15.0)
        if resp.status_code != 200:
            print(f"  [FAIL] Verification returned HTTP {resp.status_code}: {resp.text}")
            return False
        v_data = resp.json()
        hrs = v_data.get("hrs_result", {})
        print(f"  [PASS] Verified Response: {v_data.get('verified_response')[:50]}...")
        print(f"  [PASS] Hallucination Risk Score (HRS): {hrs.get('hrs', 0):.4f} (Tier: {hrs.get('tier')})")
        print(f"  [PASS] Evaluated Claims: {hrs.get('claims_count', 0)}")
        return True
    except Exception as exc:
        print(f"  [FAIL] Gate 4 verification failed: {exc}")
        return False


def verify_gate3_and_gate5(client: httpx.Client, api_key: str) -> bool:
    print("\n[4/5] Verifying Gate 3 (Action Assurance) & Gate 5 (Outcome Reality Verification)...")
    headers = {"X-API-Key": api_key}

    # Step A: Register Governed Tool
    tool_req = {
        "name": "quickstart.payment_capture",
        "description": "Captures customer payment against merchant account",
        "tool_type": "NATIVE",
        "egress_type": "INTERNAL_ISOLATED",
        "trust_level": "VERIFIED",
        "required_capability": "payments:capture",
        "parameters_schema": {
            "type": "object",
            "properties": {"order_id": {"type": "string"}, "amount": {"type": "number"}},
            "required": ["order_id", "amount"],
        },
        "active": True,
    }
    try:
        r_tool = client.post(f"{BASE_URL}/v1/tools", json=tool_req, headers=headers, timeout=5.0)
        if r_tool.status_code != 201:
            print(f"  [FAIL] Tool registration returned HTTP {r_tool.status_code}: {r_tool.text}")
            return False
        print(f"  [PASS] Tool Registered: '{tool_req['name']}' in Gate 3 registry")
    except Exception as exc:
        print(f"  [FAIL] Tool registration exception: {exc}")
        return False

    # Step B: Propose Action Contract
    tx_id = f"tx_qs_{uuid.uuid4().hex[:8]}"
    order_id = "ord_qs_999"
    proposal = {
        "transaction_id": tx_id,
        "tool_name": "quickstart.payment_capture",
        "action_type": "WRITE",
        "target_resource": f"orders:{order_id}",
        "parameters": {"order_id": order_id, "amount": 99.0},
        "idempotency_key": f"idem_qs_{uuid.uuid4().hex[:12]}",
        "postconditions": [
            {
                "assertion": "STATUS_EQUALS",
                "target": f"orders:{order_id}.status",
                "expected_value": "CAPTURED",
                "description": "Order status must transition to CAPTURED",
            }
        ],
        "blast_radius": {
            "resource_scope": "PAYMENTS",
            "estimated_dollar_cost": 99.0,
            "reversibility": "REVERSIBLE",
            "target_environment": "DEV",
        },
    }
    try:
        r_prop = client.post(f"{BASE_URL}/v1/actions/propose", json=proposal, headers=headers, timeout=5.0)
        if r_prop.status_code != 200:
            print(f"  [FAIL] Action proposal returned HTTP {r_prop.status_code}: {r_prop.text}")
            return False
        dec = r_prop.json()
        print(f"  [PASS] Gate 3 Action Contract: {dec.get('action_id')} -> Decision: {dec.get('decision')}")

        action_id = dec.get("action_id")
        if dec.get("decision") == "ALLOW":
            # Execute Action Contract
            r_exec = client.post(
                f"{BASE_URL}/v1/actions/execute",
                json={"action_id": action_id},
                headers=headers,
                timeout=5.0,
            )
            if r_exec.status_code == 200:
                exec_state = r_exec.json().get("state")
                print(f"  [PASS] Executed Action Contract through Governed Tool Proxy (State: {exec_state})")

            # Gate 5 Outcome Assurance
            obs_req = {
                "action_id": action_id,
                "expected_postconditions": {"status": "CAPTURED"},
                "observation": {
                    "observer_identity": "quickstart_mock_ledger",
                    "observed_state": {"order_id": order_id, "status": "CAPTURED"},
                    "evidence_source": "DIRECT_DATABASE_PROBE",
                },
            }
            r_out = client.post(
                f"{BASE_URL}/v1/outcomes/verify",
                json=obs_req,
                headers=headers,
                timeout=5.0,
            )
            if r_out.status_code in (200, 201):
                out_data = r_out.json()
                print(f"  [PASS] Gate 5 Reality Verification: Status={out_data.get('outcome_status')} "
                      f"(Confidence: {out_data.get('epistemic_confidence', 0)*100:.1f}%)")
        return True
    except Exception as exc:
        print(f"  [FAIL] Gate 3 / Gate 5 validation exception: {exc}")
        return False


def verify_mcp_bridge(client: httpx.Client, api_key: str) -> bool:
    print("\n[5/5] Verifying Governed MCP (Model Context Protocol) Bridge...")
    headers = {"X-API-Key": api_key}
    rpc_req = {
        "jsonrpc": "2.0",
        "id": "qs-mcp-1",
        "method": "tools/list",
        "params": {},
    }
    try:
        resp = client.post(f"{BASE_URL}/v1/mcp/rpc", json=rpc_req, headers=headers, timeout=5.0)
        if resp.status_code != 200:
            print(f"  [FAIL] MCP RPC returned HTTP {resp.status_code}: {resp.text}")
            return False
        rpc_res = resp.json()
        tools = rpc_res.get("result", {}).get("tools", [])
        tool_names = [t.get("name") for t in tools]
        print(f"  [PASS] Governed MCP Tools Exposed: {len(tools)} tools ({', '.join(tool_names)})")
        return True
    except Exception as exc:
        print(f"  [FAIL] MCP bridge check exception: {exc}")
        return False


def main() -> None:
    print_banner()
    with httpx.Client() as client:
        if not check_health(client):
            sys.exit(1)

        tenant = provision_sandbox_tenant(client)
        if not tenant:
            sys.exit(1)

        api_key = tenant["api_key"]

        g4_ok = verify_gate4_output_assurance(client, api_key)
        g3_g5_ok = verify_gate3_and_gate5(client, api_key)
        mcp_ok = verify_mcp_bridge(client, api_key)

    print("\n" + "=" * 70)
    if g4_ok and g3_g5_ok and mcp_ok:
        print("  [SUCCESS] QUICKSTART COMPLETED SUCCESSFULLY!")
        print("  MIRAGE 3.0 Platform is fully operational across all 5 Gates.")
        print("=" * 70)
        print("\nNext steps:")
        print("  1. Run Python SDK examples:")
        print("     python sdk/examples/01_verify_completion.py")
        print("     python sdk/examples/02_action_governance_and_outcome.py")
        print("     python sdk/examples/04_mcp_server_governance.py")
        print("\n  2. Open the React 18 Operator Dashboard:")
        print("     http://localhost:3000")
        print("\n  3. Connect Claude Desktop / Cursor MCP Server:")
        print("     Command: python -m mcp_server.server --tenant-id " + tenant["tenant_id"])
        print("\n  4. View Grafana Telemetry & Prometheus Metrics:")
        print("     http://localhost:3001 (Grafana) | http://localhost:9090 (Prometheus)")
        print()
    else:
        print("  [WARNING] QUICKSTART COMPLETED WITH WARNINGS.")
        print("  Check logs above for specific gate warnings.")
        print("=" * 70 + "\n")


if __name__ == "__main__":
    main()
